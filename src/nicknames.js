// Прозвище для двух карт (номиналы 2–14) или null.
export function nicknameFor(rankA, rankB) {
  const hi = Math.max(rankA, rankB), lo = Math.min(rankA, rankB);
  const ch = (r) => R[14 - r];
  return NICKNAMES[ch(hi) + ch(lo)] ?? null;
}
